<?php
declare(strict_types=1);
putenv('APP_ENV=local');
putenv('LUMS_DB_DSN=sqlite::memory:');
putenv('LUMS_SESSION_PATH='.sys_get_temp_dir().'/lums-checkout-'.bin2hex(random_bytes(8)));
require dirname(__DIR__).'/src/bootstrap.php';
initialize_database(db(),true);
start_lums_session();
$expect=static function(bool $ok,string $name):void { if(!$ok) throw new RuntimeException($name); echo "PASS: $name\n"; };
$token=bin2hex(random_bytes(16)); $now=utc_now();
db()->prepare("INSERT INTO rooms(code,name,building,floor,capacity,status,qr_token,created_at,updated_at) VALUES ('CHECK','ห้องทดสอบ','อาคาร','1',40,'available',?,?,?)")->execute([$token,$now,$now]);
$room=(int)db()->lastInsertId();
$input=['person_code'=>'660001','person_name'=>'ผู้ทดสอบ','person_role'=>'student','purpose'=>'ทดสอบ','client_request_id'=>bin2hex(random_bytes(16)),'planned_end_at'=>date('Y-m-d\TH:i',time()+3600)];
$visit=record_room_visit($token,$input,bin2hex(random_bytes(32)));
$expect($visit['ok'],'visit is created with planned end');
$found=find_active_checkout($token,'660001');
$expect(count($found)===1 && $found[0]['kind']==='visit','identifier locates active visit in room');
$expect(!confirm_room_checkout($token,'660002','visit',$visit['id'])['ok'],'another identifier cannot close visit');
$expect(confirm_room_checkout($token,'660001','visit',$visit['id'])['ok'],'correct identifier confirms checkout');
$expect(!confirm_room_checkout($token,'660001','visit',$visit['id'])['ok'],'repeated checkout does not alter recorded time');
$input['person_code']='660003'; $input['client_request_id']=bin2hex(random_bytes(16));
$second=record_room_visit($token,$input,bin2hex(random_bytes(32)));
$deadline=gmdate('Y-m-d\TH:i:s\Z',time()-60);
db()->prepare('UPDATE room_visits SET planned_end_at=? WHERE id=?')->execute([$deadline,$second['id']]);
close_expired_room_usage(db());
$q=db()->prepare('SELECT check_out_at,auto_closed_at FROM room_visits WHERE id=?');$q->execute([$second['id']]);$closed=$q->fetch();
$expect($closed['check_out_at']===$deadline && $closed['auto_closed_at']!==null,'timeout uses planned end, clearly marked');
$admin=(int)db()->query("SELECT id FROM users WHERE role='admin' LIMIT 1")->fetchColumn();
$_SESSION['user_id']=$admin; $_SESSION['last_activity']=time();
$start=date('Y-m-d\TH:i',time()-300);$end=date('Y-m-d\TH:i',time()+3600);
$class=create_class_session(['room_id'=>$room,'lecturer_user_id'=>$admin,'course_code'=>'T101','course_name'=>'คลาสทดสอบ','starts_at'=>$start,'ends_at'=>$end]);
$expect($class['ok'],'class created');
$session=get_class_session((int)$class['id']);
$student=register_student_attendance($session['qr_token'],['student_code'=>'660004','student_name'=>'ผู้ทดสอบคลาส','client_request_id'=>'checkout-class-test-01']);
$expect($student['ok'],'class attendance records deadline');
$found=find_active_checkout($token,'660004');
$expect(count($found)===1 && $found[0]['kind']==='class','class attendance can be found with room QR');
$expect(confirm_room_checkout($token,'660004','class',(int)$student['id'])['ok'],'class attendance can check out');
$student2=register_student_attendance($session['qr_token'],['student_code'=>'660005','student_name'=>'ผู้ทดสอบหมดเวลา','client_request_id'=>'checkout-class-test-02']);
$expect($student2['ok'],'second class attendance can check in');
db()->prepare('UPDATE attendance_records SET checkout_deadline_at=? WHERE id=?')->execute([$deadline,$student2['id']]);
close_expired_room_usage(db());
$q=db()->prepare('SELECT check_out_at,checkout_method FROM attendance_records WHERE id=?');$q->execute([$student2['id']]);$closed=$q->fetch();
$expect($closed['check_out_at']===$deadline && $closed['checkout_method']==='timeout','class timeout uses scheduled deadline');
echo "Checkout checks passed\n";
